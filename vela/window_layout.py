"""Construct and wire the main window's three columns.

This builder installs named controls on Window; ui.Window owns their actions
and lifecycle. Keep construction order: preview callbacks reference controls
created later but cannot fire until the window finishes initialization.
No game configuration is written by this builder.
"""
from pathlib import Path
from PySide6.QtCore import QSettings, QSize, QTimer, Qt
from PySide6.QtGui import QIcon
from PySide6.QtWidgets import QAbstractSpinBox, QLayout, QButtonGroup, QCheckBox, QFormLayout, QFrame, QHBoxLayout, QMenu, QWidgetAction, QLabel, QPlainTextEdit, QPushButton, QSplitter, QVBoxLayout, QWidget, QStyle, QGraphicsOpacityEffect
from .animation import ButtonGlow, ButtonMotion, PageMotion
from . import mangohud
from .panels import FrostedPanel
from .preview import Preview
from .notifications import Notification, ElidedLabel
from .controls import NoWheelComboBox, ApplicationComboBox, PathEdit, NoWheelSpinBox, NumberControl, SettingsScroll

from .layout_helpers import section, divider
from .appearance_layout import build_customization


def build_window(window):
    """Create customization (left), native preview (center), limiter (right)."""
    # 1. Root splitter and reusable section helpers.
    outer = QHBoxLayout(window)
    outer.setContentsMargins(20, 20, 20, 20)
    outer.setSpacing(0)
    splitter = QSplitter(Qt.Horizontal)
    splitter.setHandleWidth(18)
    outer.addWidget(splitter)
    sidebar = FrostedPanel()
    sidebar.setObjectName('sidebar')
    sidebar.setFixedWidth(268)
    sidebar_layout = QVBoxLayout(sidebar)
    sidebar_layout.setContentsMargins(6, 6, 6, 6)
    sidebar_layout.setSpacing(0)
    scroll = SettingsScroll()
    sidebar_layout.addWidget(scroll, 1)
    scroll.setWidgetResizable(True)
    scroll.setVerticalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    settings_content = QWidget()
    settings_content.setObjectName('settingsContent')
    scroll.setWidget(settings_content)
    settings_content.setAutoFillBackground(False)
    panel = QVBoxLayout(settings_content)
    panel.setSizeConstraint(QLayout.SetMinAndMaxSize)
    panel.setContentsMargins(13, 15, 13, 15)
    panel.setSpacing(0)

    title = QLabel('Customization')
    title.setObjectName('panelTitle')
    panel.addWidget(title)
    panel.addSpacing(18)
    tab_container = QFrame()
    tab_container.setObjectName('customizationTabs')
    tabs = QHBoxLayout(tab_container)
    tabs.setContentsMargins(2, 2, 2, 2)
    tabs.setSpacing(0)
    window.tabs = QButtonGroup(window)
    window.simple = QPushButton('Simple')
    window.advanced = QPushButton('Advanced')
    for button in (window.simple, window.advanced):
        button.setObjectName('tab')
        button.setCheckable(True)
        window.tabs.addButton(button)
        tabs.addWidget(button)
    window.simple.setChecked(True)
    panel.addWidget(tab_container)
    panel.addSpacing(24)
    application_group = QVBoxLayout()
    application_group.setSpacing(12)
    application_heading = QLabel('Application')
    application_heading.setObjectName('sectionTitle')
    application_group.addWidget(application_heading)
    window.process = ApplicationComboBox()
    window.process.setAccessibleName('Application with MangoHud')
    window.process.currentIndexChanged.connect(window.selection_changed)
    application_group.addWidget(window.process)
    right_sidebar = FrostedPanel()
    right_sidebar.setObjectName('sidebar')
    right_sidebar.setFixedWidth(268)
    right_layout = QVBoxLayout(right_sidebar)
    right_layout.setContentsMargins(6, 6, 6, 6)
    right_layout.setSpacing(0)
    right_scroll = SettingsScroll()
    right_scroll.setWidgetResizable(True)
    right_scroll.setVerticalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    right_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    right_content = QWidget()
    right_content.setObjectName('settingsContent')
    right_scroll.setWidget(right_content)
    right_content.setAutoFillBackground(False)
    right_layout.addWidget(right_scroll, 1)
    limits = QVBoxLayout(right_content)
    limits.setContentsMargins(13, 15, 13, 15)
    limits.setSpacing(0)
    limiter_header = QWidget()
    header_layout = QVBoxLayout(limiter_header)
    header_layout.setContentsMargins(13, 15, 13, 0)
    header_layout.setSpacing(0)
    limit_title = QLabel('Frame limiter')
    limit_title.setObjectName('panelTitle')
    header_layout.addWidget(limit_title)
    header_layout.addSpacing(18)
    header_layout.addLayout(application_group)
    divider(header_layout, 16)
    right_layout.insertWidget(0, limiter_header)
    limits.setContentsMargins(13, 0, 13, 15)
    limiter_section = section(limits, 'Limit')
    window.show_hud = QCheckBox('Show overlay')
    window.show_hud.setChecked(True)
    window.fps = NoWheelSpinBox()
    # Qt spin boxes normally take keyboard focus on wheel input, even
    # when wheelEvent ignores the value change. Focus only by click/Tab.
    window.fps.setFocusPolicy(Qt.StrongFocus)
    window.fps.lineEdit().setFocusPolicy(Qt.StrongFocus)
    window.fps.setRange(0, 1000)
    window.fps.setDecimals(0)
    window.fps.setSingleStep(1)
    window.fps.setButtonSymbols(QAbstractSpinBox.NoButtons)
    window.fps.setValue(60)
    window.fps.setAlignment(Qt.AlignCenter)
    window.fps.setSuffix(' FPS')
    window.fps.setSpecialValueText('0 · Unlimited')
    window.fps.setAccessibleName('FPS limit')
    form = QFormLayout()
    form.setRowWrapPolicy(QFormLayout.WrapAllRows)
    form.setVerticalSpacing(8)
    fps_control = NumberControl(window.fps)
    window.fps_down = fps_control.down
    window.fps_up = fps_control.up
    form.addRow('FPS limit', fps_control)
    limiter_section.addLayout(form)
    window.preview_settings = FrostedPanel()
    window.preview_settings.setObjectName('sidebar')
    window.preview_settings.setFixedWidth(268)
    settings_layout = QVBoxLayout(window.preview_settings)
    settings_layout.setContentsMargins(18, 18, 18, 18)
    settings_layout.setSpacing(0)
    preview_section = section(settings_layout, 'Preview')
    window.pause_preview = QCheckBox('Pause animation')
    window.restart_preview = QPushButton('Restart preview')
    preview_section.addWidget(window.show_hud)
    window.show_hud.toggled.connect(lambda visible: window.preview.set_overlay(visible))
    preview_section.addWidget(window.pause_preview)
    preview_section.addWidget(window.restart_preview)
    window.pause_preview.toggled.connect(lambda paused: window.preview.set_paused(paused))
    window.restart_preview.clicked.connect(window.restart_scene)
    simple_layout = build_customization(window, panel)
    window.advanced_panel = QWidget()
    advanced_layout = QVBoxLayout(window.advanced_panel)
    advanced_layout.setContentsMargins(0, 0, 0, 0)
    advanced_layout.setSpacing(0)
    window.pacing_panel = QWidget()
    pacing_layout = QVBoxLayout(window.pacing_panel)
    pacing_layout.setContentsMargins(0, 0, 0, 0)
    pacing_layout.setSpacing(0)
    divider(pacing_layout, 8)
    pacing_section = section(pacing_layout, 'Pacing')
    limits.addWidget(window.pacing_panel)
    window.method = NoWheelComboBox()
    window.method.addItem('Early · smooth pacing', 'early')
    window.method.addItem('Late · low latency', 'late')
    pacing_section.addWidget(QLabel('Limiter mode'))
    pacing_section.addWidget(window.method)
    # 4. Optional LSFG ordering controls and configuration editor.
    window.experimental_panel = FrostedPanel()
    window.experimental_panel.setObjectName('sidebar')
    window.experimental_panel.setFixedWidth(268)
    experimental_layout = QVBoxLayout(window.experimental_panel)
    experimental_layout.setContentsMargins(18, 18, 18, 18)
    experimental_layout.setSpacing(0)
    experimental_title = QLabel('Experimental functions')
    experimental_title.setObjectName('panelTitle')
    experimental_layout.addWidget(experimental_title)
    experimental_layout.addSpacing(18)
    compatibility_section = section(experimental_layout, 'Compatibility')
    fix_row = QHBoxLayout()
    fix_row.setSpacing(10)
    window.fix_lsfg = QPushButton('Fix LSFG')
    window.fix_lsfg.clicked.connect(window.configure_lsfg)
    window.remove_lsfg = QPushButton()
    window.remove_lsfg.setIcon(QIcon(str(Path(__file__).parent / 'assets/trash.svg')))
    window.remove_lsfg.setIconSize(QSize(18, 18))
    window.remove_lsfg.setObjectName('helpIcon')
    window.remove_lsfg.setFixedSize(28, 28)
    window.remove_lsfg.setAccessibleName('Remove LSFG fix')
    window.remove_lsfg.setToolTip('Remove the LSFG fix configuration and Vela layer manifests. Restart the game afterwards.')
    window.remove_lsfg.clicked.connect(window.remove_lsfg_fix)
    window.remove_lsfg.hide()
    window.lsfg_help = QPushButton()
    window.lsfg_help.setIcon(QIcon(str(Path(__file__).parent / 'assets/help.svg')))
    window.lsfg_help.setIconSize(QSize(18, 18))
    window.lsfg_help.setObjectName('helpIcon')
    window.lsfg_help.setFixedSize(28, 28)
    window.lsfg_help.setFocusPolicy(Qt.NoFocus)
    window.lsfg_help.setAccessibleName('About Fix LSFG')
    explanation = (
        'Creates a Vulkan Loader configuration that places MangoHud before lsfg-vk.\n'
        'The FPS limit applies to base frames before frame generation.\n'
        'MangoHud then counts base FPS, not the generated frames.\n'
        'Restart the game for the new layer order to take effect.\n'
        'This does not enable LSFG or change its multiplier.'
    )
    window.lsfg_help.setToolTip('Explain how Fix LSFG works')
    window.lsfg_help.clicked.connect(window.show_lsfg_help)
    window.fix_lsfg.setToolTip(explanation)
    fix_row.addWidget(window.fix_lsfg, 1)
    fix_row.addWidget(window.remove_lsfg)
    fix_row.addWidget(window.lsfg_help)
    compatibility_section.addLayout(fix_row)
    divider(experimental_layout, 16)
    reshade_section = section(experimental_layout, 'ReShade')
    reshade_placeholder = QLabel('No options configured yet.')
    reshade_placeholder.setWordWrap(True)
    reshade_placeholder.setStyleSheet('color: #888888; font-size: 12px;')
    reshade_section.addWidget(reshade_placeholder)
    experimental_layout.addStretch(1)

    window.preferences = QSettings('Vela', 'Vela')
    try:
        saved_width = int(window.preferences.value('window_width', 1400))
    except (TypeError, ValueError, OverflowError):
        saved_width = 1400
    try:
        saved_height = int(window.preferences.value('window_height', 780))
    except (TypeError, ValueError, OverflowError):
        saved_height = 780
    window.resize(max(window.minimumWidth(), min(saved_width, window.maximumWidth())),
                max(window.minimumHeight(), min(saved_height, window.maximumHeight())))
    window.config_path = PathEdit(str(window.preferences.value(
        'global_config', str(mangohud.default_config()))))
    window.config_path.setAccessibleName('Global MangoHud configuration')
    window.config_path.setToolTip('Preview inherits this file; FPS, limiter mode and overlay controls override it only in the preview.')
    config_row = QWidget()
    config_layout = QHBoxLayout(config_row)
    config_layout.setContentsMargins(0, 0, 0, 0)
    config_layout.setSpacing(6)
    config_layout.addWidget(window.config_path, 1)
    window.browse_config = QPushButton('…')
    window.browse_config.setFixedWidth(32)
    window.browse_config.setAccessibleName('Choose MangoHud configuration')
    config_layout.addWidget(window.browse_config)
    config_section = section(advanced_layout, 'Configuration')
    config_section.addWidget(QLabel('Global MangoHud file'))
    config_section.addWidget(config_row)
    window.open_config_directory = QPushButton('Open directory')
    window.open_config_directory.setIcon(QIcon.fromTheme('folder-open',
        window.style().standardIcon(QStyle.SP_DirOpenIcon)))
    window.open_config_directory.clicked.connect(window.open_configuration_directory)
    config_section.addWidget(window.open_config_directory)
    window.config_contents = QPlainTextEdit()
    window.config_contents.setReadOnly(True)
    window.config_contents.setAccessibleName('Global configuration contents')
    window.config_contents.setMinimumHeight(180)
    window.config_contents.setMaximumHeight(260)
    window.config_contents.setStyleSheet('QPlainTextEdit { background: #111111; color: #aaaaaa; border: 1px solid #2c2c2c; border-radius: 5px; padding: 8px; font-family: monospace; font-size: 11px; }')
    config_section.addSpacing(6)
    config_section.addWidget(QLabel('File contents'))
    config_section.addWidget(window.config_contents)
    window.advanced.toggled.connect(lambda active: window.update_config_contents() if active else None)
    window.config_path.editingFinished.connect(window.change_global_config)
    window.browse_config.clicked.connect(window.choose_global_config)
    panel.addWidget(window.advanced_panel)
    window.advanced_panel.hide()
    window.page_motion = PageMotion(window, (simple_layout, advanced_layout))
    window.advanced.toggled.connect(window.page_motion.start)
    window.advanced.toggled.connect(window.advanced_panel.setVisible)
    window.advanced.toggled.connect(lambda active: window.simple_panel.setVisible(not active))
    window.advanced.toggled.connect(lambda _: QTimer.singleShot(0, lambda: (settings_content.adjustSize(), scroll.verticalScrollBar().setValue(0), scroll.update_fade())))
    window.advanced.toggled.connect(lambda _: window.refresh() if hasattr(window, "sessions") else None)
    # Future MangoHud controls can be added to this scrollable panel.
    panel.addSpacing(24)
    panel.addStretch()
    window.save_config = QPushButton('Save configuration')
    window.save_config.setObjectName('apply')
    window.save_glow = ButtonGlow(window.save_config)
    window.save_config.setToolTip('Save appearance and metrics to the selected game’s existing profile, or to the global configuration if no game profile exists.')
    window.save_config.clicked.connect(window.configuration_action)
    footer = QWidget()
    footer_layout = QVBoxLayout(footer)
    footer_layout.setContentsMargins(0, 0, 0, 0)
    footer_layout.setSpacing(12)
    window.status = Notification()
    divider(limits, 16)
    buttons = QHBoxLayout()
    buttons.setSpacing(6)
    window.apply = QPushButton('Apply')
    window.apply.setObjectName('apply')
    window.apply.setDefault(True)
    window.disable = QPushButton('Disable limit')
    window.disable.setObjectName('secondary')
    window.apply.setMinimumWidth(0)
    window.disable.setMinimumWidth(0)
    buttons.addWidget(window.apply, 1)
    buttons.addWidget(window.disable, 1)
    footer_layout.addLayout(buttons)
    splitter.addWidget(sidebar)
    # 5. Native preview, toolbar, notifications and final column assembly.
    window.preview = Preview()
    center = QWidget()
    center_layout = QVBoxLayout(center)
    center_layout.setContentsMargins(0, 0, 0, 0)
    center_layout.setSpacing(0)
    window.preview_source = ElidedLabel('Global configuration')
    window.preview_source.setStyleSheet('color: #999999; font-size: 12px; padding: 0 16px;')
    window.preview_source.setFixedHeight(28)
    center_layout.addWidget(window.preview_source)
    center_layout.addWidget(window.preview, 1)
    window.preview_toolbar = QWidget()
    window.preview_toolbar.setFixedHeight(88)
    toolbar_layout = QHBoxLayout(window.preview_toolbar)
    toolbar_layout.setContentsMargins(16, 16, 16, 32)
    toolbar_layout.setSpacing(8)
    window.save_config.setMinimumWidth(240)
    window.save_config.setMaximumWidth(360)
    window.save_config.setFixedHeight(40)
    window.preview_options = QPushButton()
    window.preview_options.setIcon(QIcon(str(Path(__file__).parent / 'assets/camera.svg')))
    window.preview_options.setIconSize(QSize(20, 20))
    window.preview_options.setFixedSize(44, 40)
    window.preview_options.setCheckable(True)
    window.preview_options.setAccessibleName('Preview options')
    window.preview_options.setToolTip('Preview options')
    window.preview_options.clicked.connect(window.toggle_preview_options)
    window.settings_button = QPushButton()
    window.settings_button.setIcon(QIcon(str(Path(__file__).parent / 'assets/settings.svg')))
    window.settings_button.setIconSize(QSize(20, 20))
    window.settings_button.setFixedSize(44, 40)
    window.settings_button.setAccessibleName('Settings')
    window.settings_button.setToolTip('Settings — not configured yet')
    window.settings_button.setEnabled(False)
    toolbar_layout.addStretch(1)
    toolbar_layout.addWidget(window.save_config, 3)
    toolbar_layout.addWidget(window.preview_options)
    toolbar_layout.addWidget(window.settings_button)
    toolbar_layout.addStretch(1)
    window.preview_menu = QMenu(window)
    window.preview_menu.setStyleSheet('QMenu { background: #1b1b1d; border: 1px solid #414141; border-radius: 8px; padding: 4px; }')
    preview_action = QWidgetAction(window.preview_menu)
    preview_action.setDefaultWidget(window.preview_settings)
    window.preview_menu.addAction(preview_action)
    window.preview_menu.aboutToHide.connect(lambda: window.preview_options.setChecked(False))
    # The native transient notification stacks above the live GL window.
    center_layout.addWidget(window.preview_toolbar)
    window.status.bottom_inset = 104
    window.status.presenting.connect(window.preview.prepare_notification)
    window.status.opacity_changed.connect(window.preview.set_notification_opacity)
    window.status.dismissed.connect(window.preview.finish_notification)
    window.status.choice_closed.connect(window.finish_save_choice)
    limits.addWidget(footer)
    right_sidebar.setFixedHeight(
        limiter_header.sizeHint().height() + right_content.sizeHint().height()
        + right_scroll.frameWidth() * 2 + 60)
    splitter.addWidget(center)
    window.status.attach_to(center)
    right_column = QWidget()
    right_column.setFixedWidth(268)
    right_column_layout = QVBoxLayout(right_column)
    right_column_layout.setContentsMargins(0, 0, 0, 0)
    right_column_layout.setSpacing(12)
    right_column_layout.setSizeConstraint(QLayout.SetMinAndMaxSize)
    right_column_layout.addWidget(right_sidebar)
    right_column_layout.addWidget(window.experimental_panel, 1)
    settings_layout.addStretch()
    right_column_scroll = SettingsScroll()
    right_column_scroll.setFixedWidth(268)
    right_column_scroll.setWidgetResizable(True)
    right_column_scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    right_column_scroll.setVerticalScrollBarPolicy(Qt.ScrollBarAlwaysOff)
    right_column_scroll.setWidget(right_column)
    right_column.setAutoFillBackground(False)
    splitter.addWidget(right_column_scroll)
    splitter.setSizes([268, 800, 268])
    splitter.setStretchFactor(0, 0)
    splitter.setStretchFactor(1, 1)
    splitter.setStretchFactor(2, 0)
    splitter.setChildrenCollapsible(False)
    # Keep the pointer stable while scrolling over editable controls.
    for control in window.findChildren(QWidget):
        control.setCursor(Qt.ArrowCursor)
        if control.focusPolicy() == Qt.WheelFocus:
            control.setFocusPolicy(Qt.StrongFocus)
    # 6. Paint-only interactions and temporary configuration-choice fades.
    window.button_motion = [ButtonMotion(button) for button in window.findChildren(QPushButton) + window.findChildren(QCheckBox)]
    window.configuration_controls = (settings_content, right_content,
                                   window.preview_settings, window.preview.retry, window.preview_options,
                                   window.experimental_panel)
    window.configuration_fades = []
    for widget in window.configuration_controls:
        effect = QGraphicsOpacityEffect(widget)
        effect.setOpacity(1.)
        widget.setGraphicsEffect(effect)
        window.configuration_fades.append(effect)
